/** { omega3, omega6 } per 100 g for a row, or throws when the id has neither entry. */
export function omegaPer100(row) {
  const only = OMEGA_ONLY[row.ingredient]
  if (only) return { omega3: only[0], omega6: only[1] }
  const { omega3, omega6 } = microPer100(row)
  return { omega3, omega6 }
}

/** Per-100 g values for a row, or throws when the id has no entry. */
export function microPer100(row) {
  const variant = VARIANTS.find(v => v.id === row.ingredient && v.note.test(row.note || ''))
  const v = variant ? variant.values : MICRO[row.ingredient]
  if (v === undefined) throw new Error(`no micronutrient values for ${row.ingredient}`)
  return Object.fromEntries(COLS.map((k, i) => [k, v ? v[i] : 0]))
}
