#!/usr/bin/env node
/*
 * Salt levels and breakfast flavour for the built-in Fredheim packs.
 *
 * Two levels (decision by Fredrik, the doctor):
 *   low       the recipe as written (blood pressure, heart or kidney disease:
 *             ~1500 mg sodium a day, main meals ≤ ~600 mg). Never changed here.
 *   standard  healthy adults, WHO < 5 g salt (2000 mg sodium) a day: a main
 *             meal lands at ~650–700 mg sodium a serving (never over 750), a
 *             savoury breakfast or bread at ≤ 400 mg.
 *
 * For each recipe that is savoury, a main meal / savoury breakfast / bread,
 * and below its standard target, one salt row gets
 *   "standardAmount": <number>            (same unit as the row)
 *   "standardUnit": "tsp"                 (only on a "to taste" row, unit "")
 * in en, no and sv, and nutrition.sodiumStandard holds the per-serving sodium
 * at that level. A savoury recipe with no salt row of its own gets one,
 * "to taste" at low and a measured amount at standard. Only plain salt (or
 * the recipe's own herb salt) is raised: canned beans, broth, soy sauce,
 * miso and bouillon stay as written. Health labels are not touched: they are
 * judged on the low-salt recipe (scripts/lib/recipeLabels.mjs).
 *
 * It also stores flavourProfile ("sweet" | "savoury") on every breakfast
 * recipe and every spread/jam, for Make my week's breakfast question. Sweet
 * recipes never get a standard salt amount.
 *
 * Reproducible: earlier standard amounts are recomputed from scratch, and a
 * salt row added by an earlier run is found again as the recipe's salt row.
 *
 * Usage:
 *   node scripts/build_salt_levels.mjs           # dry run: report only
 *   node scripts/build_salt_levels.mjs --write   # write packs + bump versions
 * Writes scripts/data/salt-level-proposals.md either way.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { needsFlavour, classifyFlavour, applySaltLevel, SKIP_WHY } from './lib/saltLevels.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const PACKS_DIR = path.join(ROOT, 'recipe-packs-template', 'packs')
const REPORT = path.join(ROOT, 'scripts', 'data', 'salt-level-proposals.md')
export const PACK_FILES = ['fredheim-recipes-with-pictures.json', 'fredheim-reversal-protocol.json', 'fredheim-fmd-5day.json']

// ── report ──────────────────────────────────────────────────────────────────
const fmtAmount = (q, unit) => {
  if (q == null) return 'to taste'
  const whole = Math.floor(q)
  const frac = { 0: '', 0.25: '¼', 0.5: '½', 0.75: '¾' }[Math.round((q - whole) * 100) / 100] ?? String(q - whole)
  return `${whole ? whole : ''}${whole && frac ? ' ' : ''}${frac || (whole ? '' : '0')} ${unit}`.trim()
}

function report(rows, skipped, flavours) {
  const lines = ['# Salt levels: standard amounts', '',
    'Generated by `node scripts/build_salt_levels.mjs --write`. Low salt = the recipe as written (blood pressure, heart or kidney disease). Standard = healthy adults, WHO < 5 g salt a day: main meals ~650–700 mg sodium a serving (cap 750), savoury breakfasts and bread ≤ 400 mg. Only plain salt (or the recipe\'s own herb salt) is raised; canned beans, broth, soy sauce, miso and bouillon stay as written. Health labels are judged on the low-salt version.', '',
    `## Recipes with a standard amount (${rows.length})`, '',
    '| Recipe | Pack | Kind | Row | Low salt | Standard | Sodium/serving low → standard |',
    '|---|---|---|---|---|---|---|']
  for (const x of rows) {
    lines.push(`| ${x.title} (\`${x.id}\`) | ${x.pack} | ${x.cls} | ${x.rowName}${x.added ? ' (new row)' : ''} | ${fmtAmount(x.lowQ, x.lowUnit)} | ${fmtAmount(x.stdQ, x.stdUnit)} | ${Math.round(x.low)} → ${x.standard} mg |`)
  }
  lines.push('', `## Skipped (${skipped.length})`, '')
  const byWhy = new Map()
  for (const s of skipped) byWhy.set(s.why, [...(byWhy.get(s.why) || []), s])
  for (const [why, list] of byWhy) {
    lines.push(`### ${SKIP_WHY[why] || why} (${list.length})`, '')
    lines.push(list.map(s => `${s.title}${s.low != null ? ` (${Math.round(s.low)} mg)` : ''}`).join('; '), '')
  }
  const sweet = flavours.filter(f => f.profile === 'sweet')
  const sav = flavours.filter(f => f.profile === 'savoury')
  lines.push(`## Breakfast and spread flavour (${sweet.length} sweet, ${sav.length} savoury)`, '',
    '| Recipe | Category | Flavour | Why |', '|---|---|---|---|')
  for (const f of flavours) lines.push(`| ${f.title} (\`${f.id}\`) | ${f.category} | ${f.profile} | ${f.why} |`)
  return lines.join('\n') + '\n'
}

function bumpMinor(v) {
  const [a, b] = String(v || '1.0.0').split('.').map(Number)
  return `${a}.${(b || 0) + 1}.0`
}

function main(argv) {
  const write = argv.includes('--write')
  const dict = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/data/ingredientDictionary.json'), 'utf8'))
  const dictById = new Map(dict.entries.map(e => [e.id, e]))
  const rows = []
  const skipped = []
  const flavours = []
  const versions = {}
  for (const file of PACK_FILES) {
    const full = path.join(PACKS_DIR, file)
    const text = fs.readFileSync(full, 'utf8')
    const pack = JSON.parse(text)
    const before = JSON.stringify(pack.recipes)
    for (const r of pack.recipes) {
      if (needsFlavour(r)) {
        const f = classifyFlavour(r)
        r.flavourProfile = f.profile
        flavours.push({ id: r.id, title: r.title, category: r.category, ...f })
      } else delete r.flavourProfile
      const res = applySaltLevel(r, dictById)
      if (res.skipped) { skipped.push({ id: r.id, title: r.title, why: res.skipped, low: res.low }); continue }
      rows.push({
        id: r.id, title: r.title, pack: pack.id, cls: res.cls, low: res.low, standard: res.standard, added: res.added,
        rowName: res.row.ingredient, lowQ: res.row.quantity, lowUnit: res.row.unit,
        stdQ: res.row.standardAmount, stdUnit: res.row.standardUnit || res.row.unit,
      })
    }
    if (JSON.stringify(pack.recipes) !== before) {
      pack.version = bumpMinor(pack.version)
      versions[pack.id] = pack.version
      if (write) fs.writeFileSync(full, JSON.stringify(pack, null, 2) + '\n', 'utf8')
    }
  }
  fs.writeFileSync(REPORT, report(rows, skipped, flavours), 'utf8')
  console.log(JSON.stringify({
    write, standard: rows.length, skipped: skipped.length,
    flavour: { sweet: flavours.filter(f => f.profile === 'sweet').length, savoury: flavours.filter(f => f.profile === 'savoury').length },
    versions: write ? versions : `(dry run; would bump ${Object.keys(versions).join(', ') || 'nothing'})`,
    report: path.relative(ROOT, REPORT),
  }, null, 1))
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2))
